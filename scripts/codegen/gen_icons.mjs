// Regenerates src/lib/icons-fill.generated.ts: the FILL-weight SVG body of every
// Phosphor icon imported by src/lib/icons.tsx. Phosphor ships all 6 weights per
// icon module (~283 kB in the entry chunk); the app only ever renders "fill".
//
// Run after adding an icon to the list in src/lib/icons-names.ts:
//   node scripts/codegen/gen_icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const require = createRequire(join(root, "package.json"));
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");

const names = [...readFileSync(join(root, "src/lib/icons-names.ts"), "utf8").matchAll(/"([A-Za-z0-9]+)"/g)].map((m) => m[1]);
const defsDir = join(dirname(require.resolve("@phosphor-icons/react")), "defs");

const out = {};
for (const name of names) {
  const mod = await import(join(defsDir, `${name}.es.js`));
  const weights = mod.default;
  const el = weights.get("fill");
  if (!el) throw new Error(`no fill weight for ${name}`);
  out[name] = renderToStaticMarkup(React.createElement(React.Fragment, null, el));
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n");
writeFileSync(
  join(root, "src/lib/icons-fill.generated.ts"),
  `// GENERATED by scripts/codegen/gen_icons.mjs from @phosphor-icons/react (fill weight). Do not edit.\n` +
    `export const FILL = {\n${body}\n} as const;\n\nexport type FillIconName = keyof typeof FILL;\n`,
);
console.log(`wrote ${names.length} icons`);
